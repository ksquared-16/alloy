/**
 * D4 — the household document library's shapes, shared by the server read model and the client.
 *
 * No server imports here: the Focus Panel bundle reads these.
 */
export const LIBRARY_SUBJECT_TYPES = ["household", "person", "child", "opportunity"] as const;
export type LibrarySubjectType = (typeof LIBRARY_SUBJECT_TYPES)[number];
export type LibrarySubjectRef = { subject_type: LibrarySubjectType; subject_id: string };

export function isLibrarySubjectType(value: unknown): value is LibrarySubjectType {
    return typeof value === "string" && (LIBRARY_SUBJECT_TYPES as readonly string[]).includes(value);
}

/** The legacy `documents.entity_type` an upload to this subject is filed under (the D2 trigger maps it back). */
export const LIBRARY_UPLOAD_ENTITY_TYPE: Record<LibrarySubjectType, string> = {
    household: "customer",
    person: "person",
    child: "customer_member",
    opportunity: "opportunity",
};

export type LibrarySubject = LibrarySubjectRef & {
    label: string;
    /** household | adult (parent/guardian) | child | case */
    role: "household" | "adult" | "child" | "case";
    is_primary_contact: boolean;
    active: boolean;
};

export type LibraryAssociation = LibrarySubjectRef & {
    association: "owner" | "context";
    is_primary: boolean;
    /** `document_subjects`, or the derived source (`form_submission_documents:<role>`, …). */
    derived_from: string;
};

export type LibraryDocumentType = {
    key: string | null;
    label: string;
    /** True when the key names a type this organization configured in Studio. */
    registered: boolean;
    category_id: string | null;
    category_label: string | null;
};

export type LibraryVersion = {
    id: string;
    version_number: number;
    created_at: string | null;
    source: string | null;
    /** Authoritative review and validity columns of the version, as stored. Never derived here. */
    review_status: string | null;
    effective_on: string | null;
    expires_on: string | null;
};

export type LibraryDocument = {
    id: string;
    title: string;
    original_filename: string | null;
    mime_type: string | null;
    byte_size: number | null;
    type: LibraryDocumentType;
    sensitivity: string;
    status: string | null;
    received_at: string | null;
    /** The primary owner when it is part of this household; null when the document is owned elsewhere. */
    owner: LibrarySubjectRef | null;
    /** The document is owned outside this household and appears here only through an association. */
    owned_elsewhere: boolean;
    /** Every link from this document to a subject of this household (owner or context), primary first. */
    associations: LibraryAssociation[];
    /** Linked to a form submission of one of the household's cases, or generated by Forms. */
    forms_artifact: boolean;
    current_version: LibraryVersion | null;
    version_count: number;
};

export type DocumentLibrary = {
    anchor: LibrarySubjectRef;
    household: { id: string; label: string } | null;
    subjects: LibrarySubject[];
    focus: LibrarySubjectRef | null;
    documents: LibraryDocument[];
    categories: Array<{ id: string; label: string; parent_id: string | null }>;
    /** More documents are linked than one response carries. */
    truncated: boolean;
};
