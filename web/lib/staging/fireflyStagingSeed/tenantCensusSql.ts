/**
 * Firefly staging tenant census — renders `supabase/seed/firefly_staging_tenant_census.sql` (ALY-14 E3).
 *
 * READ ONLY. Answers, before the seed is applied to hosted staging, whether the Firefly tenant's own
 * configuration has what the seed binds families to. Every row is `section | key | expected | actual |
 * verdict`. Expectations come from the dataset and lifecycleTarget.ts, the same definitions the seed's
 * gate, binding and refusal use (renderSql.ts), so the census cannot ask about a department the seed does
 * not bind to. A test fails if the committed file and this renderer ever differ.
 */

import { SEED_SITES, SEED_PROGRAM_CATEGORIES, buildSeedFamilies } from "./dataset";
import { FIREFLY_ORG_ID, RETIRED_SEPARATE_ORG_ID, SEED_ID_PREFIX } from "./ids";
import {
    FIREFLY_ACTIVE_PROCESS_KEY,
    FIREFLY_LIFECYCLE_DEPARTMENT_ID_OBSERVED,
    FIREFLY_LIFECYCLE_DEPARTMENT_KEY,
    FIREFLY_LIFECYCLE_WORK_UNIT_KEYS,
    FIREFLY_PROCESS_STAGE_KEYS,
    FIREFLY_UNBOUND_DEPARTMENT_KEY,
} from "./lifecycleTarget";
import { OPEN_FAMILY_STAGES } from "./renderSql";
import { STAGING_PROJECT_REF } from "./targets";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** The seed's family stages that are not in Firefly's process (closed cases): reported, never required. */
export const SEED_STAGES_OUTSIDE_PROCESS = [...new Set(buildSeedFamilies().map((f) => f.stage))].filter(
    (s) => !(FIREFLY_PROCESS_STAGE_KEYS as readonly string[]).includes(s),
);

function siteRows(): string {
    return SEED_SITES.map((site, ord) => {
        const keys = SEED_PROGRAM_CATEGORIES.filter((c) => c.site === site.key).map((c) => q(c.key));
        return `    (${q(site.key)}, ${ord}, ARRAY[${keys.join(", ")}])`;
    }).join(",\n");
}

export function renderFireflyStagingTenantCensusSql(): string {
    const stageList = (keys: readonly string[]) => keys.map((k) => `(${q(k)})`).join(", ");
    const sortedStages = [...FIREFLY_PROCESS_STAGE_KEYS].sort().join(",");
    return `-- Firefly staging tenant census (ALY-14 E3) — READ ONLY.
-- GENERATED by web/lib/staging/fireflyStagingSeed/tenantCensusSql.ts. Do not edit by hand:
--   cd web && npm run staging:seed:firefly -- render
--
-- TARGET: hosted staging, Supabase project ${STAGING_PROJECT_REF}; org Firefly Early Learning
-- ${FIREFLY_ORG_ID}; its lifecycle department keyed \`${FIREFLY_LIFECYCLE_DEPARTMENT_KEY}\` (metadata.lifecycle_builder_v1),
-- whose active process is \`${FIREFLY_ACTIVE_PROCESS_KEY}\` with ${FIREFLY_PROCESS_STAGE_KEYS.length} stages and ${FIREFLY_LIFECYCLE_WORK_UNIT_KEYS.length} lifecycle_wu_<stage> queues
-- (web/lib/staging/fireflyStagingSeed/lifecycleTarget.ts). Firefly's department keyed \`${FIREFLY_UNBOUND_DEPARTMENT_KEY}\` is reported,
-- never bound. Never run against production.
--
-- Answers whether the tenant's own configuration has what \`firefly_staging_seed.sql\` binds families to:
--   sites             the seed's north / south / west take the tenant's active sites in this order
--                     (is_primary DESC, location_number, label, id), wrapping when there are fewer
--   program keys      a child's program is the tenant's category of that key at its bound site
--   lifecycle         exactly one tenant department keyed ${FIREFLY_LIFECYCLE_DEPARTMENT_KEY}, with an active ${FIREFLY_ACTIVE_PROCESS_KEY} process and its stages
--   queues            each lifecycle stage has an active lifecycle_wu_<stage> in that department; every
--                     open seeded stage must, or the seed refuses
--
-- Every answer is a row \`section | key | expected | actual | verdict\`; nothing is written. Rows are
-- the tenant's own (ids outside the seed namespace \`${SEED_ID_PREFIX}\`). FAIL means a seeded open
-- case would be unbound or the seed would refuse; WARN means the seed still binds but more coarsely than
-- its dataset (fewer than three sites, a missing program key) or an identifying detail differs from the
-- last observation; INFO is reported only.
--
--   psql "$DB" -X -v ON_ERROR_STOP=1 -P pager=off -A -F ' | ' -f supabase/seed/firefly_staging_tenant_census.sql

BEGIN READ ONLY;

WITH
firefly AS (SELECT ${q(FIREFLY_ORG_ID)}::uuid AS id),
seed_sites(site_key, ord, expected_programs) AS (VALUES
${siteRows()}
),
process_stage_keys(stage) AS (VALUES ${stageList(FIREFLY_PROCESS_STAGE_KEYS)}),
open_seed_stages(stage) AS (VALUES ${stageList(OPEN_FAMILY_STAGES)}),
outside_stages(stage) AS (VALUES ${stageList(SEED_STAGES_OUTSIDE_PROCESS)}),
tenant_sites AS (
    SELECT l.id, l.label, l.location_number, l.is_primary,
           row_number() OVER (ORDER BY l.is_primary DESC NULLS LAST, l.location_number NULLS LAST, l.label, l.id) - 1 AS rn,
           count(*) OVER () AS n
    FROM public.locations l, firefly f
    WHERE l.org_id = f.id AND l.location_type = 'site' AND l.is_active
      AND l.id::text NOT LIKE '${SEED_ID_PREFIX}%'
),
bound_sites AS (
    SELECT k.site_key, k.ord, k.expected_programs, s.id, s.label, s.location_number
    FROM seed_sites k LEFT JOIN tenant_sites s ON s.rn = k.ord % s.n
),
lifecycle AS (
    SELECT d.id, d.is_active, d.metadata->'lifecycle_builder_v1' AS builder
    FROM public.departments d, firefly f
    WHERE d.org_id = f.id AND d.key = ${q(FIREFLY_LIFECYCLE_DEPARTMENT_KEY)} AND d.id::text NOT LIKE '${SEED_ID_PREFIX}%'
),
active_process AS (
    SELECT p
    FROM lifecycle d CROSS JOIN LATERAL jsonb_array_elements(coalesce(d.builder->'processes', '[]'::jsonb)) p
    WHERE p->>'id' = d.builder->>'active_process_id'
),
process_stages AS (
    SELECT DISTINCT st->>'key' AS stage_key
    FROM active_process a CROSS JOIN LATERAL jsonb_array_elements(coalesce(a.p->'stages', '[]'::jsonb)) st
),
lifecycle_queues AS (
    SELECT w.key, w.is_active FROM public.work_units w JOIN lifecycle d ON w.department_id = d.id
),
answers(section, key, expected, actual, verdict, ord) AS (
    SELECT 'org', 'firefly_org', 'present',
           CASE WHEN EXISTS (SELECT 1 FROM public.orgs o, firefly f WHERE o.id = f.id) THEN 'present' ELSE 'absent' END,
           NULL::text, 10
    UNION ALL
    SELECT 'org', 'retired_separate_staging_org', 'absent',
           CASE WHEN EXISTS (SELECT 1 FROM public.orgs WHERE id = ${q(RETIRED_SEPARATE_ORG_ID)}::uuid) THEN 'present' ELSE 'absent' END,
           NULL, 11
    UNION ALL
    SELECT 'org', 'seed_rows_already_present', 'informational',
           (SELECT count(*)::text FROM public.customers c, firefly f WHERE c.org_id = f.id AND c.id::text LIKE '${SEED_ID_PREFIX}%'),
           'INFO', 12
    UNION ALL
    SELECT 'sites', 'tenant_active_sites', '>= 1 (3 for one site per seed campus)',
           (SELECT count(*)::text FROM tenant_sites), NULL, 20
    UNION ALL
    SELECT 'sites', 'bound_' || b.site_key, 'a tenant site',
           coalesce(b.label || ' (#' || coalesce(b.location_number::text, '-') || ', ' || b.id || ')', '<unbound>'),
           NULL, 21 + b.ord
    FROM bound_sites b
    UNION ALL
    SELECT 'programs', b.site_key || ':' || k.key || ' @ ' || coalesce(b.label, '<unbound site>'), 'present',
           CASE WHEN EXISTS (
               SELECT 1 FROM public.location_program_categories c, firefly f
               WHERE c.org_id = f.id AND c.location_id = b.id AND c.key = k.key AND c.is_active
           ) THEN 'present' ELSE 'absent' END,
           NULL, 30 + b.ord
    FROM bound_sites b CROSS JOIN LATERAL unnest(b.expected_programs) AS k(key)
    UNION ALL
    SELECT 'programs', 'tenant_keys_at_' || b.site_key, 'informational',
           coalesce((SELECT string_agg(c.key, ',' ORDER BY c.key) FROM public.location_program_categories c, firefly f
                     WHERE c.org_id = f.id AND c.location_id = b.id AND c.is_active), '<none>'),
           'INFO', 35 + b.ord
    FROM bound_sites b
    UNION ALL
    SELECT 'lifecycle', 'lifecycle_department', '1', (SELECT count(*)::text FROM lifecycle), NULL, 40
    UNION ALL
    -- The key is the binding; the id is the last observation, so a different id is a WARN, not a FAIL.
    SELECT 'lifecycle', 'lifecycle_department_id', ${q(FIREFLY_LIFECYCLE_DEPARTMENT_ID_OBSERVED)},
           coalesce((SELECT id::text FROM lifecycle LIMIT 1), '<absent>'), NULL, 41
    UNION ALL
    SELECT 'lifecycle', 'lifecycle_department_is_active', 'true',
           coalesce((SELECT is_active::text FROM lifecycle LIMIT 1), '<absent>'), NULL, 42
    UNION ALL
    SELECT 'lifecycle', 'lifecycle_builder_v1', 'present',
           CASE WHEN EXISTS (SELECT 1 FROM lifecycle WHERE builder IS NOT NULL) THEN 'present' ELSE 'absent' END, NULL, 43
    UNION ALL
    SELECT 'lifecycle', 'active_process_id', 'set',
           coalesce((SELECT builder->>'active_process_id' FROM lifecycle LIMIT 1), '<none>'), NULL, 44
    UNION ALL
    SELECT 'lifecycle', 'active_process_key', ${q(FIREFLY_ACTIVE_PROCESS_KEY)},
           coalesce((SELECT p->>'key' FROM active_process LIMIT 1), '<none>'), NULL, 45
    UNION ALL
    SELECT 'lifecycle', 'active_process_is_active', 'true',
           coalesce((SELECT p->>'is_active' FROM active_process LIMIT 1), '<unset>'), NULL, 46
    UNION ALL
    SELECT 'lifecycle', 'active_process_stage_count', ${q(String(FIREFLY_PROCESS_STAGE_KEYS.length))},
           (SELECT count(*)::text FROM process_stages), NULL, 47
    UNION ALL
    SELECT 'lifecycle', 'active_process_stage_keys', ${q(sortedStages)},
           coalesce((SELECT string_agg(stage_key, ',' ORDER BY stage_key) FROM process_stages), '<none>'), NULL, 48
    UNION ALL
    SELECT 'process', 'stage_' || s.stage, 'in active process',
           CASE WHEN EXISTS (SELECT 1 FROM process_stages p WHERE p.stage_key = s.stage) THEN 'in active process' ELSE 'absent' END,
           NULL, 50
    FROM process_stage_keys s
    UNION ALL
    -- Seeded closed cases sit in these stages; Firefly's process has none, so they are in no lane.
    SELECT 'process', 'stage_' || s.stage, 'informational (seed closed cases; not a Firefly stage)',
           CASE WHEN EXISTS (SELECT 1 FROM process_stages p WHERE p.stage_key = s.stage) THEN 'in active process' ELSE 'absent' END,
           'INFO', 51
    FROM outside_stages s
    UNION ALL
    SELECT 'queues', 'lifecycle_wu_' || s.stage, 'active',
           CASE WHEN EXISTS (SELECT 1 FROM lifecycle_queues w WHERE w.key = 'lifecycle_wu_' || s.stage AND w.is_active) THEN 'active'
                WHEN EXISTS (SELECT 1 FROM lifecycle_queues w WHERE w.key = 'lifecycle_wu_' || s.stage) THEN 'inactive'
                ELSE 'absent' END,
           NULL, 60
    FROM process_stage_keys s
    UNION ALL
    SELECT 'queues', 'active_lifecycle_work_units', ${q(String(FIREFLY_LIFECYCLE_WORK_UNIT_KEYS.length))},
           (SELECT count(*)::text FROM lifecycle_queues WHERE key LIKE 'lifecycle\\_wu\\_%' AND is_active), NULL, 61
    UNION ALL
    -- The seed's own refusal condition: every open seeded stage needs an active queue here.
    SELECT 'queues', 'open_seed_stages_with_queue', ${q(String(OPEN_FAMILY_STAGES.length))},
           (SELECT count(*)::text FROM open_seed_stages s
            WHERE EXISTS (SELECT 1 FROM lifecycle_queues w WHERE w.key = 'lifecycle_wu_' || s.stage AND w.is_active)), NULL, 62
    UNION ALL
    SELECT 'queues', 'tenant_work_unit_keys', 'informational',
           coalesce((SELECT string_agg(key || CASE WHEN is_active THEN '' ELSE '(inactive)' END, ',' ORDER BY key)
                     FROM lifecycle_queues), '<none>'),
           'INFO', 68
    UNION ALL
    SELECT 'departments', 'firefly_department_keys', 'informational',
           coalesce((SELECT string_agg(d.key, ',' ORDER BY d.key) FROM public.departments d, firefly f
                     WHERE d.org_id = f.id AND d.id::text NOT LIKE '${SEED_ID_PREFIX}%'), '<none>'),
           'INFO', 69
    UNION ALL
    SELECT 'departments', ${q(`unbound_department:${FIREFLY_UNBOUND_DEPARTMENT_KEY}`)}, 'informational (never bound)',
           coalesce((SELECT 'present; active_process_id=' || coalesce(d.metadata->'lifecycle_builder_v1'->>'active_process_id', '<none>')
                     FROM public.departments d, firefly f
                     WHERE d.org_id = f.id AND d.key = ${q(FIREFLY_UNBOUND_DEPARTMENT_KEY)} AND d.id::text NOT LIKE '${SEED_ID_PREFIX}%'), 'absent'),
           'INFO', 69
    UNION ALL
    -- Managed QA identities (\`qa-slot<N>-…@example.com\`, the only shape the toolkit provisions) and
    -- the Firefly roles they hold. E3 wants exactly three; the toolkit's access step grants \`admin\` in
    -- DEV_QUEUE_ORG_ID, which may already have put earlier slot identities here.
    SELECT 'qa_identities', 'managed_qa_accounts', 'informational',
           (SELECT count(*)::text FROM auth.users u WHERE u.email ~* '^qa-slot[0-9]+-[a-z0-9-]+@example\\.com$'),
           'INFO', 70
    UNION ALL
    SELECT 'qa_identities', 'firefly_member:' || u.email, 'informational',
           (SELECT string_agg(r.role, ',' ORDER BY r.role) FROM public.user_roles r, firefly f WHERE r.user_id = u.id AND r.org_id = f.id),
           'INFO', 71
    FROM auth.users u
    WHERE u.email ~* '^qa-slot[0-9]+-[a-z0-9-]+@example\\.com$'
      AND EXISTS (SELECT 1 FROM public.user_roles r, firefly f WHERE r.user_id = u.id AND r.org_id = f.id)
    UNION ALL
    SELECT 'qa_identities', 'firefly_managed_qa_members', '3',
           (SELECT count(DISTINCT u.id)::text FROM auth.users u JOIN public.user_roles r ON r.user_id = u.id, firefly f
            WHERE r.org_id = f.id AND u.email ~* '^qa-slot[0-9]+-[a-z0-9-]+@example\\.com$'),
           NULL, 72
    UNION ALL
    -- The installed access step first creates a "QA Operator · Slot N" person fixture in the org.
    SELECT 'qa_identities', 'firefly_qa_person_fixtures', 'informational',
           (SELECT count(*)::text FROM public.persons p, firefly f WHERE p.org_id = f.id AND p.external_source = 'alloy_qa_fixture'),
           'INFO', 72
    UNION ALL
    -- Shared-QA (ZZ Alloy QA) identities must never hold a Firefly membership.
    SELECT 'qa_identities', 'shared_qa_accounts_in_firefly', '0',
           (SELECT count(DISTINCT u.id)::text FROM auth.users u JOIN public.user_roles r ON r.user_id = u.id, firefly f
            WHERE r.org_id = f.id AND u.email ~* '^qa-(shared-actor|secondary-admin|pool-[0-9]+)@example\\.com$'),
           NULL, 73
)
SELECT section, key, expected, actual,
       coalesce(verdict,
           CASE
               WHEN expected = actual THEN 'PASS'
               WHEN key = 'tenant_active_sites' AND actual::int >= 3 THEN 'PASS'
               WHEN key = 'tenant_active_sites' AND actual::int >= 1 THEN 'WARN'
               WHEN key LIKE 'bound_%' AND actual <> '<unbound>' THEN 'PASS'
               -- the seed still writes; that child's program is left unbound
               WHEN section = 'programs' AND expected = 'present' THEN 'WARN'
               WHEN key = 'active_process_id' AND actual <> '<none>' THEN 'PASS'
               WHEN key = 'lifecycle_department_id' AND actual <> '<absent>' THEN 'WARN'
               WHEN key = 'active_process_is_active' AND actual = '<unset>' THEN 'WARN'
               ELSE 'FAIL'
           END) AS verdict
FROM answers
ORDER BY ord, section, key;

ROLLBACK;
`;
}

export type CensusVerdict = "PASS" | "WARN" | "FAIL" | "INFO";
export type CensusRow = { section: string; key: string; expected: string; actual: string; verdict: CensusVerdict };

/**
 * FAIL rows the runbook does not stop on: `firefly_managed_qa_members` reads 6 by owner decision
 * (§2.3 of firefly-staging-qa-profile.md — earlier slot identities are kept and recorded).
 */
export const NON_BLOCKING_FAIL_KEYS = Object.freeze(["firefly_managed_qa_members"]);

/** psql `-A -t -F '|'` output → rows. Lines that are not five fields ending in a verdict are skipped. */
export function parseTenantCensusOutput(stdout: string): CensusRow[] {
    const rows: CensusRow[] = [];
    for (const raw of stdout.split(/\r?\n/)) {
        const parts = raw.split("|").map((p) => p.trim());
        if (parts.length < 5) continue;
        const verdict = parts[parts.length - 1];
        if (!["PASS", "WARN", "FAIL", "INFO"].includes(verdict)) continue;
        // A key or actual may itself contain `|` only in no row this census emits; join defensively.
        rows.push({
            section: parts[0],
            key: parts[1],
            expected: parts[2],
            actual: parts.slice(3, -1).join("|"),
            verdict: verdict as CensusVerdict,
        });
    }
    return rows;
}

export type CensusSummary = {
    counts: Record<CensusVerdict, number>;
    blocking: CensusRow[];
    /** Keys the renderer emits that the output lacks: a truncated or wrong-file run. */
    missingKeys: string[];
    /** True only when every fixed row is present and no blocking FAIL exists. */
    seedMayProceed: boolean;
};

/** Keys every run must print, independent of the tenant's data (sites, programs and members vary). */
export function requiredCensusKeys(): string[] {
    return [
        "firefly_org",
        "retired_separate_staging_org",
        "lifecycle_department",
        "lifecycle_department_id",
        "lifecycle_department_is_active",
        "lifecycle_builder_v1",
        "active_process_id",
        "active_process_key",
        "active_process_is_active",
        "active_process_stage_count",
        "active_process_stage_keys",
        ...FIREFLY_PROCESS_STAGE_KEYS.map((s) => `stage_${s}`),
        ...FIREFLY_LIFECYCLE_WORK_UNIT_KEYS,
        "active_lifecycle_work_units",
        "open_seed_stages_with_queue",
        `unbound_department:${FIREFLY_UNBOUND_DEPARTMENT_KEY}`,
        "firefly_managed_qa_members",
        "shared_qa_accounts_in_firefly",
    ];
}

export function summarizeTenantCensus(rows: CensusRow[]): CensusSummary {
    const counts: Record<CensusVerdict, number> = { PASS: 0, WARN: 0, FAIL: 0, INFO: 0 };
    for (const r of rows) counts[r.verdict] += 1;
    const blocking = rows.filter((r) => r.verdict === "FAIL" && !NON_BLOCKING_FAIL_KEYS.includes(r.key));
    const present = new Set(rows.map((r) => r.key));
    const missingKeys = requiredCensusKeys().filter((k) => !present.has(k));
    return { counts, blocking, missingKeys, seedMayProceed: blocking.length === 0 && missingKeys.length === 0 };
}

/** The operator-facing report: the target, then expected vs observed per row, then the stop-rule answer. */
export function formatTenantCensusReport(rows: CensusRow[], target: { projectRef: string | null; host: string }): string {
    const s = summarizeTenantCensus(rows);
    const lines = [
        "Firefly staging tenant census — READ ONLY",
        `  project       ${target.projectRef ?? `<none> (host ${target.host})`}`,
        `  org           ${FIREFLY_ORG_ID} (Firefly Early Learning)`,
        `  department    key ${FIREFLY_LIFECYCLE_DEPARTMENT_KEY} (lifecycle_builder_v1); last observed id ${FIREFLY_LIFECYCLE_DEPARTMENT_ID_OBSERVED}`,
        `  process       ${FIREFLY_ACTIVE_PROCESS_KEY}; stages ${FIREFLY_PROCESS_STAGE_KEYS.join(", ")}`,
        `  queues        ${FIREFLY_LIFECYCLE_WORK_UNIT_KEYS.length} × lifecycle_wu_<stage>`,
        "",
    ];
    const width = Math.max(10, ...rows.map((r) => r.key.length));
    let section = "";
    for (const r of rows) {
        if (r.section !== section) {
            section = r.section;
            lines.push(`[${section}]`);
        }
        lines.push(`  ${r.verdict.padEnd(4)}  ${r.key.padEnd(width)}  expected: ${r.expected}  observed: ${r.actual}`);
    }
    lines.push(
        "",
        `rows ${rows.length}: ${s.counts.PASS} PASS, ${s.counts.WARN} WARN, ${s.counts.FAIL} FAIL, ${s.counts.INFO} INFO`,
    );
    if (s.missingKeys.length) lines.push(`MISSING rows (wrong file or truncated output): ${s.missingKeys.join(", ")}`);
    lines.push(
        s.seedMayProceed
            ? `stop rule: no blocking FAIL — step 2 may be proposed to the owner (non-blocking: ${NON_BLOCKING_FAIL_KEYS.join(", ")})`
            : `stop rule: STOP — blocking FAIL: ${s.blocking.map((r) => r.key).join(", ") || "<none>"}`,
    );
    return lines.join("\n");
}
