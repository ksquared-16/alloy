function preflight(): string {
    return `${section("Preflight refusals")}
DO $preflight$
DECLARE
    v_target text := current_setting('firefly_seed.target');
    v_existing_slug text;
    v_slug_owner uuid;
BEGIN
    IF v_target NOT IN ('local', 'staging') THEN
        RAISE EXCEPTION 'firefly_staging_seed: refused — seed_target % is not a designated target', v_target;
    END IF;

    -- The fence counts rows. A role that RLS filters would count only what it can see.
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = current_user AND (rolsuper OR rolbypassrls)) THEN
        RAISE EXCEPTION 'firefly_staging_seed: refused — role % does not bypass RLS, so the fence could not see every row', current_user;
    END IF;

    -- No global writes: the industry must already be there.
    IF NOT EXISTS (SELECT 1 FROM public.industries WHERE key = 'childcare' AND is_active) THEN
        RAISE EXCEPTION 'firefly_staging_seed: refused — industry childcare is missing; this database is not migrated';
    END IF;

    SELECT slug INTO v_existing_slug FROM public.orgs WHERE id = ${uuid(SEED_ORG_ID)};
    IF v_existing_slug IS NOT NULL AND v_existing_slug <> ${lit(SEED_ORG_SLUG)} THEN
        RAISE EXCEPTION 'firefly_staging_seed: refused — org ${SEED_ORG_ID} exists with slug %, not ${SEED_ORG_SLUG}', v_existing_slug;
    END IF;
    SELECT id INTO v_slug_owner FROM public.orgs WHERE slug = ${lit(SEED_ORG_SLUG)};
    IF v_slug_owner IS NOT NULL AND v_slug_owner <> ${uuid(SEED_ORG_ID)} THEN
        RAISE EXCEPTION 'firefly_staging_seed: refused — slug ${SEED_ORG_SLUG} belongs to org %', v_slug_owner;
    END IF;

    IF v_target = 'local' AND EXISTS (SELECT 1 FROM public.orgs WHERE id = ${uuid(LIVE_FIREFLY_ORG_ID)}) THEN
        RAISE EXCEPTION 'firefly_staging_seed: refused — target local holds the live Firefly tenant; this is not the local stack';
    END IF;
END $preflight$;
`;
}

function fenceOpen(): string {
    return `${section("Fence: count every row outside the seed org")}
CREATE TEMP TABLE firefly_seed_fence (
    schema_name  text   NOT NULL,
    table_name   text   NOT NULL,
    scope_column text,
    outside_rows bigint NOT NULL,
    PRIMARY KEY (schema_name, table_name)
) ON COMMIT DROP;

DO $fence_open$
DECLARE
    r record;
    v_scope text;
    v_count bigint;
BEGIN
    FOR r IN
        SELECT n.nspname AS schema_name, c.relname AS table_name, c.oid AS rel
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE c.relkind = 'r' AND n.nspname IN (${FENCE_SCHEMAS.map(lit).join(", ")})
        ORDER BY 1, 2
    LOOP
        v_scope := CASE
            WHEN r.schema_name = 'public' AND r.table_name = 'orgs' THEN 'id'
            WHEN EXISTS (
                SELECT 1 FROM pg_attribute a
                WHERE a.attrelid = r.rel AND a.attname = 'org_id' AND NOT a.attisdropped
                  AND a.atttypid = 'uuid'::regtype
            ) THEN 'org_id'
            ELSE NULL
        END;
        IF v_scope IS NULL THEN
            EXECUTE format('SELECT count(*) FROM %I.%I', r.schema_name, r.table_name) INTO v_count;
        ELSE
            EXECUTE format('SELECT count(*) FROM %I.%I WHERE %I IS DISTINCT FROM $1', r.schema_name, r.table_name, v_scope)
                INTO v_count USING ${uuid(SEED_ORG_ID)};
        END IF;
        INSERT INTO firefly_seed_fence VALUES (r.schema_name, r.table_name, v_scope, v_count);
    END LOOP;
END $fence_open$;
`;
}

function fenceClose(): string {
    return `${section("Fence: prove nothing outside the seed org changed")}
DO $fence_close$
DECLARE
    f record;
    v_count bigint;
    v_written bigint;
    v_violations text[] := ARRAY[]::text[];
    v_tables int := 0;
BEGIN
    FOR f IN SELECT * FROM firefly_seed_fence ORDER BY schema_name, table_name LOOP
        v_tables := v_tables + 1;
        IF f.scope_column IS NULL THEN
            EXECUTE format('SELECT count(*), count(*) FILTER (WHERE age(xmin) <= 0) FROM %I.%I', f.schema_name, f.table_name)
                INTO v_count, v_written;
        ELSE
            EXECUTE format(
                'SELECT count(*), count(*) FILTER (WHERE age(xmin) <= 0) FROM %I.%I WHERE %I IS DISTINCT FROM $1',
                f.schema_name, f.table_name, f.scope_column
            ) INTO v_count, v_written USING ${uuid(SEED_ORG_ID)};
        END IF;
        IF v_count <> f.outside_rows OR v_written > 0 THEN
            v_violations := v_violations || format('%I.%I (outside rows %s -> %s, written %s)',
                f.schema_name, f.table_name, f.outside_rows, v_count, v_written);
        END IF;
    END LOOP;
    -- A table created during the run is a write outside the seed org by definition.
    IF EXISTS (
        SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE c.relkind = 'r' AND n.nspname IN (${FENCE_SCHEMAS.map(lit).join(", ")})
          AND NOT EXISTS (SELECT 1 FROM firefly_seed_fence x WHERE x.schema_name = n.nspname AND x.table_name = c.relname)
    ) THEN
        v_violations := v_violations || 'a table appeared during the seed'::text;
    END IF;
    IF array_length(v_violations, 1) IS NOT NULL THEN
        RAISE EXCEPTION 'firefly_staging_seed: FENCE — rows outside org ${SEED_ORG_ID} changed; rolled back: %',
            array_to_string(v_violations, '; ');
    END IF;
    RAISE NOTICE 'firefly_staging_seed: fence held — % tables, 0 rows changed outside org ${SEED_ORG_ID}', v_tables;
END $fence_close$;
`;
}

