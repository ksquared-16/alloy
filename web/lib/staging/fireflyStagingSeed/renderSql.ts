/**
 * Firefly staging seed — renders the dataset to one self-contained psql script (ALY-14 E2).
 *
 * The script is the unit of review: `supabase/seed/firefly_staging_seed.sql` is this function's
 * output, committed, and a test fails if the two ever differ.
 *
 * SAFETY, IN THE ORDER IT RUNS
 *   1. Refuses unless the runner set `seed_target` (local | staging) — psql -v seed_target=…
 *   2. One REPEATABLE READ transaction. Nothing is visible to anyone until every check below passes.
 *   3. Preflight refusals: the role must bypass RLS (so the fence counts every row); `childcare`
 *      must already exist (the seed writes no global row); the seed's org id / slug must not belong
 *      to someone else; a LOCAL target that holds the live Firefly tenant is not the local stack.
 *   4. THE FENCE. Before writing, it counts every row OUTSIDE the seed org in every table of the
 *      public, auth and storage schemas (`org_id IS DISTINCT FROM seed org`; `orgs.id` for orgs;
 *      every row for a table with no org_id). After writing it counts again, and counts rows this
 *      transaction wrote (`age(xmin) <= 0`) outside the seed org. Any difference raises, and the
 *      whole seed rolls back. So "no write outside the designated org" is not a claim about this
 *      file's text — it is measured in the database on every run, triggers included.
 *   5. Writes: upserts keyed on fixed ids, with fixed values (no now(), no random), so a re-run
 *      converges every seeded row back to its known state.
 *
 * NOT WRITTEN: identities (auth.users, user_roles, access profiles) — E3 — and no DELETE anywhere.
 * No `\ir`: the script is fed on stdin when the only psql is the stack's own container.
 */

