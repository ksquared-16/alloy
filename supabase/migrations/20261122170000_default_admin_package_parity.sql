-- W7 pre-QA (Director, 2026-10-09) — THE DEFAULT ADMINISTRATOR PACKAGE MATCHES THE ADMIN CONTRACT.
--
-- Read-only comparison on certification: a NEW organization's `admin` held every active catalogue
-- key except six. Each was classified from the migration that introduced it:
--
--   fin.provider              ADMIN_SHOULD_HAVE. 20260920120000: admin only, deliberately not ops.
--                             Granted to every EXISTING admin at the time; never added here. An active
--                             Financials capability, so it blocks W7 under the Director rule.
--   integrations.read/manage  ADMIN_SHOULD_HAVE. 20260912000000 granted every existing admin and relied
--                             on the new-org seed for new organizations; the seed never carried them.
--   staff.compensation.read/write
--                             ADMIN_SHOULD_HAVE. 20260928120000: owner and admin only, granted to every
--                             existing admin; never added here.
--   attendance.record.assigned_only
--                             INTENTIONALLY_WITHHELD. A restriction flag, active and granted to nobody
--                             (20260911140000). Not added.
--
-- So this is seed drift, not a contract change: existing administrators already hold the five keys.
-- The function is re-declared verbatim from 20260916050000 with exactly those five added to the
-- explicit ADMIN list; the active-catalogue guard and every other role list are unchanged, and ops
-- still receives none of them. Existing organizations are not touched. Re-runnable.
-- =============================================================================

